def seed_system_sources(session) -> int:
    """Insert system sources if they don't exist. Returns number inserted."""

    from app.models.source import SourceType, TransactionSourceConfig

    inserted = 0
    for source_id, name, source_type, check_account_id, source_config in SYSTEM_SOURCES:
        existing = session.get(TransactionSourceConfig, source_id)
        if existing is None:
            session.add(
                TransactionSourceConfig(
                    id=source_id,
                    user_id=None,
                    name=name,
                    type=SourceType(source_type),
                    check_account_id=check_account_id,
                    source_config=source_config,
                )
            )
            inserted += 1
        else:
            # Update type and check_account_id if they changed
            if existing.type.value != source_type:
                existing.type = SourceType(source_type)
            if existing.check_account_id != check_account_id:
                existing.check_account_id = check_account_id
            # Update source_config if not set or if new config has more keys
            if existing.source_config is None or (source_config and len(source_config) > len(existing.source_config or {})):
                existing.source_config = source_config
    session.commit()
    return inserted


def seed_oms_providers(session) -> bool:
    """Auto-configure the Billbee OMS provider from environment. Returns True if created.

    Fallback for the migration seed: if Billbee credentials are present but no
    provider record exists (e.g. a DB restored before the migration), create it.
    """
    from sqlalchemy import select

    from app.config import get_settings
    from app.models.oms_provider import OmsProviderRecord, OmsProviderType

    if not get_settings().billbee_api_key:
        return False

    existing = session.scalar(select(OmsProviderRecord).where(OmsProviderRecord.type == OmsProviderType.BILLBEE))
    if existing is not None:
        return False

    session.add(OmsProviderRecord(type=OmsProviderType.BILLBEE, display_name="Billbee", is_active=True))
    session.commit()
    return True
