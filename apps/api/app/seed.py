def seed_system_user(session) -> bool:
    """Ensure system user exists for Local Mode. Returns True if created.

    The system user (ID: 00000000-...) is used in Local Mode to satisfy FK
    constraints on transactions, receipts, etc. Protected from deletion.
    """
    from app.models.user import User

    existing = session.get(User, SYSTEM_USER_ID)
    if existing is None:
        session.add(
            User(
                id=SYSTEM_USER_ID,
                provider_id="local",
                provider_type="local",
                email="local@localhost",
                name="Local User",
            )
        )
        session.commit()
        return True
    return False


